"""Merge observed lexical classes by morphology, not their learned context."""
import json,pathlib
root=pathlib.Path(__file__).resolve().parents[2]
signatures=json.loads((root/'documentation/coverage/dependency-grammar-audit.json').read_text())['pool_signatures']
result={}
for name,signature in signatures.items():
 parts=signature.split('|');pos=parts[0]
 if pos not in {'NOUN','PROPN','VERB','ADJ','ADV','INTJ'}:result[name]=signature;continue
 # Keep article sound, countability, possessive spelling, and inflection;
 # discard lemma identity, attachment, semantic frame, and governor.
 keep=[p for p in parts[5:] if p.startswith(('countability=','possessiveSpelling='))]
 if 'countability=unreviewed' in keep:keep += [p for p in parts[5:] if p.startswith('unreviewedLemma=')]
 result[name]='|'.join([pos,parts[1],parts[4],*keep])
(root/'src/option3-pool-signatures.js').write_text('// Generated by tools/vocabulary/build_option3_pools.py\nexport default '+json.dumps(result,separators=(',',':'))+';\n')
